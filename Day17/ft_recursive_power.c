int	power(int nb, int pow)
{
	int	a;

	if (pow < 0)
		return (0);
	if (pow == 0)
		return (1);
	if (pow == 1)
		return (nb);
	a = 1;
	a = nb *power(nb, (pow - 1));
	return (a);
}
